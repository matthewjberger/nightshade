use crate::data::{BinaryOperator, Cardinality, UnaryOperator};

#[derive(Clone, Copy, Debug)]
pub enum Op {
    PushNumber(f32),
    PushTruth(bool),
    PushText(u32),
    PushNothing,
    PushLocal(u16),
    PopLocal(u16),
    PushSet(u16),
    PushColumn(u16),
    PushNumberColumn(u16),
    PushColumnOf(u16),
    PushField(u16),
    PushEvents(u16),
    Axis(u8),
    Index,
    Unary(UnaryOperator),
    Binary(BinaryOperator),
    MixNumber(BinaryOperator, f32),
    MixField(BinaryOperator, u16),
    MixColumn(BinaryOperator, u16),
    MakeVector(u8),
    MakeList(u8),
    IsSome,
    Builtin(u8, u8),
    CallQuery(u16, u8),
    StoreColumn(u16),
    StoreNumberColumn(u16),
    AddColumn(u16),
    AddNumberColumn(u16),
    AddColumnOf(u16),
    AddAxis(u16, u8),
    AddAxisOf(u16, u8),
    AddField(u16),
    PokeColumn(u16),
    PokeColumnOf(u16),
    PokeField(u16),
    StoreColumnOf(u16),
    StoreAxis(u16, u8),
    StoreAxisOf(u16, u8),
    StoreField(u16),
    StoreAxisField(u16, u8),
    Spawn(u16),
    Remove,
    Emit(u16),
    Jump(u32),
    JumpIfFalse(u32),
    ForNext(u16),
    SetIndex,
    Append,
    Pop,
    Keep(u16),
    Recall(u16),
    Halt,
}

#[derive(Clone, Copy, Debug)]
pub struct LoopSite {
    pub list: u16,
    pub cursor: u16,
    pub name: u16,
    pub done: u32,
}

#[derive(Clone, Debug, Default)]
pub struct Routine {
    pub code: Vec<Op>,
}

#[derive(Clone, Debug)]
pub struct Pick {
    pub roster: u16,
    pub label: u16,
    pub cardinality: Cardinality,
    pub loose: bool,
    pub need: Vec<u16>,
    pub ban: Vec<u16>,
    pub starts: Vec<(u16, Routine)>,
}

