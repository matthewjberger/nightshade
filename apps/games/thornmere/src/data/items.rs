#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Grade {
    #[default]
    Plain,
    Fine,
    Rare,
    Storied,
}

impl Grade {
    pub fn color(self) -> Vec4 {
        match self {
            Grade::Plain => Vec4::new(0.86, 0.88, 0.92, 1.0),
            Grade::Fine => Vec4::new(0.45, 0.92, 0.50, 1.0),
            Grade::Rare => Vec4::new(0.40, 0.66, 1.0, 1.0),
            Grade::Storied => Vec4::new(0.82, 0.48, 1.0, 1.0),
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Wear {
    #[default]
    Carried,
    Hand,
    Head,
    Chest,
    Charm,
}

impl Wear {
    pub fn name(self) -> &'static str {
        match self {
            Wear::Carried => "Carried",
            Wear::Hand => "Hand",
            Wear::Head => "Head",
            Wear::Chest => "Chest",
            Wear::Charm => "Charm",
        }
    }

    pub fn slot(self) -> Option<usize> {
        match self {
            Wear::Carried => None,
            Wear::Hand => Some(0),
            Wear::Head => Some(1),
            Wear::Chest => Some(2),
            Wear::Charm => Some(3),
        }
    }
}

pub const WEAR_ORDER: [Wear; WEAR_SLOTS] = [Wear::Hand, Wear::Head, Wear::Chest, Wear::Charm];

