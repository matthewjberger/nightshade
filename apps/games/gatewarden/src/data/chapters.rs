use crate::data::cards::{CardId, Element};
use crate::data::decks::HeroPower;
use crate::data::story::SceneText;

pub const CHAPTER_COUNT: usize = 8;
pub const DECK_DEPTH: usize = 14;
pub const FOE_DECK_DEPTH: usize = 16;

pub struct Chapter {
    pub title: &'static str,
    pub lines: [&'static str; 4],
    pub won: &'static str,
    pub lesson: &'static str,
    pub foe: &'static str,
    pub element: Element,
    pub power: HeroPower,
    pub health: i32,
    pub aggressive: bool,
    pub sigil: char,
    pub hand: &'static [CardId],
    pub deck: &'static [CardId],
    pub foe_deck: &'static [CardId],
    pub board: &'static [CardId],
    pub foe_board: &'static [CardId],
    pub mana: u32,
}

pub fn chapter(index: usize) -> &'static Chapter {
    let index = index.min(CHAPTER_COUNT - 1);
    &CHAPTERS[index]
}

pub fn chapter_scene(index: usize) -> SceneText {
    let sheet = chapter(index);
    SceneText {
        speaker: sheet.title,
        lines: sheet.lines,
        fork: None,
    }
}

pub fn chapter_won(index: usize) -> SceneText {
    let sheet = chapter(index);
    SceneText {
        speaker: "The road opens",
        lines: [sheet.won, "", "", ""],
        fork: None,
    }
}

pub fn story_end() -> SceneText {
    SceneText {
        speaker: "The road ends",
        lines: [
            "You know the table now. Guard and Rush, Shield and Venom, frost and drain.",
            "The eight gates are still shut, and no one hands you a deck up there.",
            "Take the climb. Buy what you can carry, cut what you cannot.",
            "",
        ],
        fork: None,
    }
}

